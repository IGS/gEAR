// Generate dynamic colors for any number of dataset types
const generateChartColors = (count) => {
    const baseColors = [
        { bg: 'rgba(54, 162, 235, 0.8)', border: 'rgb(54, 162, 235)' },
        { bg: 'rgba(75, 192, 192, 0.8)', border: 'rgb(75, 192, 192)' },
        { bg: 'rgba(255, 159, 64, 0.8)', border: 'rgb(255, 159, 64)' },
        { bg: 'rgba(153, 102, 255, 0.8)', border: 'rgb(153, 102, 255)' },
        { bg: 'rgba(255, 99, 132, 0.8)', border: 'rgb(255, 99, 132)' },
        { bg: 'rgba(255, 205, 86, 0.8)', border: 'rgb(255, 205, 86)' },
        { bg: 'rgba(201, 203, 207, 0.8)', border: 'rgb(201, 203, 207)' },
        { bg: 'rgba(54, 215, 235, 0.8)', border: 'rgb(54, 215, 235)' }
    ];

    const colors = { bg: [], border: [] };
    for (let i = 0; i < count; i++) {
        const colorIndex = i % baseColors.length;
        colors.bg.push(baseColors[colorIndex].bg);
        colors.border.push(baseColors[colorIndex].border);
    }
    return colors;
};

// Format numbers with comma separators
const formatNumber = (num) => {
    return num.toLocaleString('en-US');
};

// Format date from YYYYMMDD to readable format
const formatDateFromAnalytics = (dateStr) => {
    const year = dateStr.substring(0, 4);
    const month = dateStr.substring(4, 6);
    const day = dateStr.substring(6, 8);
    const date = new Date(`${year}-${month}-${day}`);
    return date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
};

// Format file size in GB with appropriate units
const formatFileSize = (sizeInGB) => {
    const bytes = sizeInGB * 1073741824; // 1024^3
    const units = ['B', 'KB', 'MB', 'GB', 'TB', 'PB', 'EB'];

    let unitIndex = 0;
    let size = bytes;

    while (size >= 1024 && unitIndex < units.length - 1) {
        size /= 1024;
        unitIndex++;
    }

    return `${formatNumber(+size.toFixed(2))} ${units[unitIndex]}`;
};

const capitilizeFirstLetter = (str) => {
    if (!str) return '';
    return str.charAt(0).toUpperCase() + str.slice(1);
};

